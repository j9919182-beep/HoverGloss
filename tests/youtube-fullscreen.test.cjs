"use strict";
const assert = require("node:assert/strict");
const { fixture, turn } = require("./cc-session-fixture.cjs");
(async () => {
  const f = fixture(), p = f.connect(); await f.prepare(p); f.start(p); f.advance(500);
  assert.equal(f.translations.length, 1);
  f.document.fullscreenElement = f.player; f.events.fullscreenchange(); p.disconnect();
  f.advance(2000); assert.equal(f.intervals.size, 1, "sidebar document destruction must not stop authorized fullscreen");
  f.translations[0].resolve({ translation: "全屏中文" }); await turn();
  assert.equal(f.overlays[0].pairs.at(-1).translation, "全屏中文", "inference completes without a sidebar");
  const newPanel = f.connect(), snapshot = newPanel.messages[0].snapshot;
  assert.equal(snapshot.state, "running"); assert.equal(snapshot.prepared, true); assert.equal(snapshot.session, "test-session");
  assert.equal(snapshot.history[0].translation, "全屏中文"); assert.equal(f.activations, 1, "reopening does not reload model");
  const controls = f.player.children.find((n) => n.id === "hovergloss-cc-session").shadowRoot.children[1].children;
  await controls[2].click(); assert.equal(f.intervals.size, 0, "in-player pause stops reading");
  await controls[2].click(); assert.equal(f.intervals.size, 1, "in-player continue resumes the same session");
  newPanel.disconnect(); f.document.fullscreenElement = null; f.events.fullscreenchange();
  f.advance(500); const reopened = f.connect(); f.advance(500);
  assert.equal(reopened.messages[0].snapshot.state, "running", "exit/reconnect ordering gets grace");
  reopened.disconnect(); f.advance(1100); assert.equal(f.intervals.size, 1, "closing controls keeps on-video CC running");
  const clearPanel = f.connect(); clearPanel.command({ type: "clear-history", session: "" });
  const cleared = f.connect();
  assert.equal(cleared.messages[0].snapshot.history.length, 0, "clear also works while stopped");
  cleared.command({ type: "stop" }); clearPanel.disconnect(); cleared.disconnect();
  let p2 = f.connect(); f.start(p2, { fullscreen: false }); f.document.fullscreenElement = f.player;
  f.events.fullscreenchange(); p2.disconnect(); f.advance(1100); assert.equal(f.intervals.size, 0, "opt-out forbids detached fullscreen");
  p2 = f.connect(); f.start(p2); f.events.fullscreenchange(); p2.disconnect();
  f.document.visibilityState = "hidden"; f.events.visibilitychange();
  assert.equal(f.intervals.size, 1, "hidden video continues CC processing");
  const hidden = f.connect().messages[0].snapshot;
  assert.equal(hidden.state, "running"); assert.equal(hidden.suspended, false);
  f.document.visibilityState = "visible"; f.events.visibilitychange();
  assert.equal(f.intervals.size, 1, "returning to same fullscreen video recovers CC");
  console.log("Durable fullscreen CC: sidebar teardown, in-flight completion, reconnect history/model, exit race, close, opt-out, hidden tab: passed");
})().catch((error) => { console.error(error); process.exitCode = 1; });

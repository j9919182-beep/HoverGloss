"use strict";
const assert = require("node:assert/strict");
const { analyze } = require("../french-grammar-local.js");
const first = (sentence) => analyze(sentence).sentences[0];
const text = (value) => JSON.stringify(value);
const basic = first("Je ne mange pas de viande.");
assert.match(basic.structure, /Je.*mange/);
assert.match(text(basic.verbs), /manger.*现在时.*第一人称单数/);
assert.match(text(basic.points), /否定线索/);
assert.match(text(basic.points), /否定句中的 de/);
assert.match(text(first("Nous finissons le travail.").verbs), /finir.*现在时/);
assert.match(text(first("Il y a un chat.").points), /存在/);
assert.equal(first("J’aime le français.").parts[0].text, "J");
assert.match(text(first("J’aime le français.").points), /省音线索/);
assert.match(text(first("Nous mangeons.").verbs), /manger/);
assert.match(text(first("Je mangeais.").verbs), /未完成过去时/);
assert.match(text(first("Nous commencions.").verbs), /未完成过去时/);
assert.match(text(first("Je commençais.").verbs), /commencer/);
assert.match(text(first("Elle parlera demain.").verbs), /简单将来时/);
assert.match(text(first("Je voudrais du pain.").verbs), /条件式现在时/);
assert.match(text(first("J'ai mangé du pain.").verbs), /复合过去时/);
assert.match(text(first("Elle est allée à Paris.").verbs), /复合过去时/);
assert.match(text(first("Je suis allé à Paris.").verbs), /复合过去时/);
assert.match(text(first("Je vais manger.").verbs), /最近将来时/);
assert.match(text(first("Je peux parler.").verbs), /不定式 parler/);
assert.match(text(first("Parlez-vous français ?").parts), /倒装主语线索/);
assert.equal(first("Je vous parle.").parts[0].text, "Je");
assert.equal(first("Vous nous parlez.").parts[0].text, "Vous");
assert.match(text(first("Le chat dort.").parts), /可能的名词短语主语/);
assert.match(text(first("Le livre que je lis est intéressant.").notices), /从句/);
assert.match(first("Le livre que je lis est intéressant.").structure, /尚未可靠/);
assert.equal(first("Le fait.").verbs.length, 0, "Known verb spelling after an article may be a noun");
assert.equal(first("Une porte.").verbs.length, 0);
assert.match(text(first("Je suis étudiant.").verbs), /être.*suivre/, "Do not silently resolve ambiguous suis without evidence");
assert.match(text(first("Nous parle.").notices), /不一致/);
assert.match(text(first("Les xylophones flamboient.").notices), /未找到/);
assert.match(text(first("Je parle au professeur.").points), /à \+ le/);
assert.match(text(first("Je veux du pain.").points), /部分冠词/);
assert.equal(analyze("Il a 1.5 euros. Je parle.").sentences.length, 2, "Decimal point must not break a sentence");
assert.equal(analyze("").sentences.length, 0);
assert.equal(analyze("a".repeat(3001)).sentences.length, 0);
assert.match(analyze("a".repeat(3001)).message, /超过/);
assert.equal(first("<img src=x onerror=alert(1)> Bonjour.").text, "<img src=x onerror=alert(1)> Bonjour.");
console.log("Offline French basics: common forms, compound/future patterns, clitics, ambiguity, unknown words and decimal boundaries passed.");

"use strict";
const assert = require("node:assert/strict");
const { fixture, turn } = require("./cc-session-fixture.cjs");
const snapshot = (p) => p.messages.findLast((m) => m.snapshot)?.snapshot;
(async () => {
  const f = fixture(), p = f.connect(); await f.prepare(p); f.start(p); f.advance(500);
  const before = snapshot(p);
  f.document.visibilityState = "hidden"; f.events.visibilitychange(); p.disconnect();
  assert.equal(f.intervals.size, 1, "Switching websites does not stop CC");
  f.translations[0].resolve({ translation: "后台译文" }); await turn();
  assert.equal(f.overlays[0].pairs.at(-1).translation, "后台译文", "In-flight work completes while hidden");
  f.segment.textContent = "A new background caption"; f.media.currentTime += 3; f.advance(60000);
  assert.equal(f.translations.length, 2, "CC keeps translating without a panel heartbeat");
  f.translations[1].resolve({ translation: "下一条字幕" }); await turn();
  f.document.visibilityState = "visible"; f.events.visibilitychange(); f.advance(500);
  const returned = f.connect(), after = snapshot(returned);
  assert.equal(after.state, "running"); assert.equal(after.session, before.session);
  assert.equal(after.history.length, 2); assert.equal(f.activations, 1);
  returned.disconnect(); f.advance(10000);
  assert.equal(f.intervals.size, 1, "Minimized panel does not stop on-video captions");
  const controls = f.player.children.find((n) => n.id === "hovergloss-cc-session").shadowRoot.children[1].children;
  await controls[2].click(); assert.equal(f.intervals.size, 0);
  f.document.visibilityState = "hidden"; f.events.visibilitychange();
  f.document.visibilityState = "visible"; f.events.visibilitychange();
  assert.equal(f.intervals.size, 0, "Manual pause remains paused");
  await controls[2].click(); assert.equal(f.intervals.size, 1);
  const stopped = f.connect(); stopped.command({ type: "stop" });
  f.document.visibilityState = "hidden"; f.events.visibilitychange();
  f.document.visibilityState = "visible"; f.events.visibilitychange();
  assert.equal(f.intervals.size, 0, "Manual stop remains stopped");
  f.start(stopped); f.location.href = "https://www.youtube.com/watch?v=second12345";
  f.events["yt-navigate-finish"]();
  assert.equal(f.intervals.size, 0, "New video ends old session");
  assert.equal(snapshot(f.connect()).session, "");
  console.log("CC background continuation, minimized panel, history/model reuse, manual pause/stop and navigation passed");
})().catch((error) => { console.error(error); process.exitCode = 1; });

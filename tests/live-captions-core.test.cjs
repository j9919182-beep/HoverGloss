"use strict";
const assert = require("node:assert/strict");
const { videoId, normalize, CaptionFeed, TranslationQueue } = require("../live-captions-core.js");
const turn = () => new Promise((resolve) => setImmediate(resolve));
const deferred = () => { let resolve, reject; const promise = new Promise((a, b) => { resolve = a; reject = b; }); return { promise, resolve, reject }; };

async function main() {
  assert.equal(videoId("https://www.youtube.com/watch?v=abc_123-45&t=2"), "abc_123-45");
  for (const url of ["http://youtube.com/watch?v=abc12345", "https://youtube.com.evil.test/watch?v=abc12345", "https://youtube.com/shorts/abc12345", "https://youtube.com/watch?v=abc", "not a url"]) assert.equal(videoId(url), "");
  assert.equal(normalize("  hello\n world  "), "hello world");
  assert.equal(normalize("x".repeat(1300)).length, 1200);

  const feed = new CaptionFeed();
  let events = feed.update("This is the first", 0, 5);
  assert.equal(events[0].stable, false);
  const id = events[0].id;
  assert.equal(feed.update("This is the first", 100, 5).length, 0);
  events = feed.update("This is the first example", 250, 5);
  assert.equal(events[0].text, "This is the first example");
  assert.equal(events[0].id, id);
  assert.equal(events[0].revision, 2);
  assert.equal(feed.tick(1149).length, 0);
  assert.equal(feed.tick(1150)[0].stable, true);
  assert.equal(feed.tick(1300).length, 0);
  assert.equal(feed.finish().length, 0, "do not resubmit a stable revision at row boundary");
  events = feed.update("Something else", 1800, 9);
  assert.ok(events[0].id > id);
  assert.equal(feed.finish()[0].text, "Something else");

  feed.update("the economy is changing", 2000, 10);
  events = feed.update("is changing very quickly", 2200, 10);
  assert.equal(events[0].text, "the economy is changing very quickly", "rolling overlap must not repeat words");
  feed.reset();
  feed.update("We will go tomorrow", 3000, 20);
  events = feed.update("We will go today", 3200, 20);
  assert.equal(events.length, 1);
  assert.equal(events[0].revision, 2);
  assert.equal(events[0].text, "We will go today", "revise rather than duplicate partial captions");
  events = feed.update("A completely different caption", 3400, 21);
  assert.equal(events.length, 2);
  assert.equal(events[0].stable, true);
  assert.equal(events[1].stable, false);
  feed.reset();
  feed.update("This line", 0, 0);
  events = feed.update("This line continues", 8001, 8);
  assert.equal(events[0].text, "This line");
  assert.equal(events[1].text, "continues", "limit continuously extending captions without duplicating old words");

  const operations = [], reports = [];
  const queue = new TranslationQueue((text) => { const d = deferred(); operations.push({ text, ...d }); return d.promise; }, (...args) => reports.push(args), 2);
  const row = (id, revision = 1, stable = true) => ({ id, revision, stable, text: `text ${id}/${revision}` });
  queue.observe(row(1, 1, false));
  assert.equal(operations.length, 0);
  queue.observe(row(1)); queue.observe(row(1));
  assert.equal(operations.length, 1, "one request per stable revision");
  queue.observe(row(1, 2, false)); queue.observe(row(1, 2));
  operations[0].resolve("old translation"); await turn();
  assert.equal(reports.length, 0, "stale translation must never replace revised captions");
  assert.equal(operations.length, 2);
  operations[1].resolve("new translation"); await turn();
  assert.equal(reports[0][1], "new translation");
  queue.observe(row(1, 2)); await turn();
  assert.equal(operations.length, 2, "completed stable events are deduplicated");
  queue.observe(row(2)); queue.observe(row(3)); queue.observe(row(4)); queue.observe(row(5));
  assert.equal(queue.pending.size, 2);
  assert.equal(reports.at(-1)[0].id, 3, "drop oldest pending, not newest, when local translator falls behind");
  assert.match(reports.at(-1)[2], /暂未翻译/);
  const count = reports.length;
  queue.reset(); operations[2].resolve("late after stop"); await turn();
  assert.equal(reports.length, count);
  queue.observe(row(6)); queue.forget(6); operations[3].resolve("removed row"); await turn();
  assert.equal(reports.length, count);
  queue.observe(row(7)); operations[4].reject(new Error("model failed")); await turn();
  assert.equal(reports.at(-1)[2], "model failed");
  queue.observe(row(7)); await turn();
  assert.equal(operations.length, 5, "errors do not automatically retry");
  assert.equal(queue.active, false);
  console.log("live captions core: passed");
}
main().catch((error) => { console.error(error); process.exitCode = 1; });

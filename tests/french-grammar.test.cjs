const assert = require("node:assert/strict");
const grammar = require("../french-grammar.js");
const { createHarness, analysis, sentence } = require("./grammar-fixture.cjs");
async function run() {
  assert.equal(grammar.parse(JSON.stringify(analysis), sentence).sentences[0].verbs[0].infinitive, "manger");
  assert.throws(() => grammar.parse("{", sentence), /完整/);
  assert.throws(() => grammar.validate({ ...analysis, sentences: [] }, sentence), /覆盖完整/);
  const bad = structuredClone(analysis); bad.sentences[0].parts[0].text = "Nous";
  assert.throws(() => grammar.validate(bad, sentence), /原句以外/);
  const multi = { ...analysis, sentences: [...analysis.sentences, ...analysis.sentences] };
  assert.equal(grammar.validate(multi, `${sentence} ${sentence}`).sentences.length, 2);
  assert.throws(() => grammar.validate(analysis, `${sentence} ${sentence}`), /覆盖完整/);
  const h = createHarness(), entry = await h.seed();
  const english = JSON.stringify(h.data.hoverglossLearningV1);
  const request = { type: "learningGrammar", language: "fr", id: entry.id, confirmSend: true };
  assert.equal((await h.send({ ...request, confirmSend: false })).ok, false);
  assert.equal((await h.send(request, "https://example.test/")).ok, false);
  assert.equal((await h.send({ ...request, language: "en" })).ok, false);
  assert.equal(h.requests.length, 0);
  h.data.aiKey = "";
  assert.equal((await h.send({ type: "learningGrammarStatus" })).ready, false);
  assert.equal((await h.send(request)).ok, false);
  h.data.aiKey = "test-only-key";
  const [a, b] = await Promise.all([h.send(request), h.send(request)]);
  assert.equal(a.ok, true); assert.equal(b.ok, true); assert.equal(h.requests.length, 1, "Concurrent clicks share one request");
  assert.deepEqual(JSON.parse(h.requests[0].body.messages[1].content), { sentence });
  assert.ok(!JSON.stringify(h.requests[0].body).includes("Private title"));
  assert.equal((await h.send(request)).cached, true); assert.equal(h.requests.length, 1);
  const prior = JSON.stringify((await h.store.list("fr"))[0].grammar);
  h.state.reply = async () => ({ ok: false, status: 429 });
  assert.match((await h.send({ ...request, regenerate: true })).error, /429/);
  h.state.reply = async () => ({ ok: true, json: async () => ({ choices: [{ message: { content: JSON.stringify(bad) } }] }) });
  assert.equal((await h.send({ ...request, regenerate: true })).ok, false);
  assert.equal(JSON.stringify((await h.store.list("fr"))[0].grammar), prior, "Failed regeneration retains saved analysis");
  h.state.reply = async () => { const error = new Error("aborted"); error.name = "AbortError"; throw error; };
  assert.match((await h.send({ ...request, regenerate: true })).error, /超时/);
  assert.equal(JSON.stringify((await h.store.list("fr"))[0].grammar), prior);
  await h.store.edit(entry.id, { meaning: "肉类", notes: "我的笔记" }, "fr");
  await h.store.review(entry.id, "remember", "fr");
  assert.equal(JSON.stringify((await h.store.list("fr"))[0].grammar), prior);
  assert.equal(JSON.stringify(h.data.hoverglossLearningV1), english, "English library is untouched");
  let release;
  h.state.reply = () => new Promise((resolve) => { release = resolve; });
  const pending = h.send({ ...request, regenerate: true });
  while (!release) await new Promise((resolve) => setImmediate(resolve));
  await h.store.remove(entry.id, "fr");
  release({ ok: true, json: async () => ({ choices: [{ message: { content: JSON.stringify(analysis) } }] }) });
  assert.match((await pending).error, /已删除/);
  assert.equal((await h.store.list("fr")).length, 0);
  console.log("French grammar validation, manual-only requests, deduplication, caching, privacy and safe persistence passed (AI mocked).");
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
